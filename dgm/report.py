"""Phase 8: numbers for the report, formatted exactly as the notebooks print them (spec: notes/phase8_spec.md).

  num          a value at a fixed number of decimals, with an explicit sign if asked, as f"{x:.3f}"
               does (so -0.0895 -> -0.090, matching every notebook table); LaTeX minus in math mode
  ci           "lo to hi" as the notebooks print a 95% CI
  macro_name   a LaTeX command name from words (letters only; digits spelled out)
  macros       the text of report/numbers.tex: one \\newcommand per value
  latex_table  a booktabs table from rows of already formatted strings
"""
from __future__ import annotations

import re

DIGITS = {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four", "5": "Five", "6": "Six", "7": "Seven", "8": "Eight", "9": "Nine"}


def num(x: float, places: int = 3, sign: bool = False, latex: bool = True) -> str:
    """x as the notebooks print it (f"{x:.{places}f}"), optionally with a leading "+"; in LaTeX the
    minus is $-$ so it typesets as a minus sign."""
    s = f"{x:+.{places}f}" if sign else f"{x:.{places}f}"
    if s.lstrip("+-") == f"{0:.{places}f}":
        s = s.lstrip("+-") if not sign else "+" + s.lstrip("+-")        # no "-0.000"
    return s.replace("-", "$-$") if latex else s


def ci(lo: float, hi: float, places: int = 3, latex: bool = True) -> str:
    return f"{num(lo, places, latex=latex)} to {num(hi, places, latex=latex)}"


def macro_name(*words) -> str:
    """\\HOneSBMargin-style name: each word capitalized, digits spelled out, everything else dropped."""
    out = ""
    for w in words:
        w = "".join(DIGITS.get(ch, ch) for ch in str(w))
        out += "".join(part[:1].upper() + part[1:] for part in re.split(r"[^A-Za-z]+", w) if part)
    assert out and out.isalpha(), words
    return out


def macros(values: dict) -> str:
    """{name: text} -> the lines of a .tex file of \\newcommand definitions (sorted, so reruns are identical)."""
    lines = ["% Generated by notebooks/phase8_figures.ipynb from results/phaseN/*.csv. Do not edit by hand."]
    for k in sorted(values):
        assert re.fullmatch(r"[A-Za-z]+", k), k
        lines.append(f"\\newcommand{{\\{k}}}{{{values[k]}}}")
    return "\n".join(lines) + "\n"


def latex_table(header: list, rows: list, align: str | None = None, caption: str | None = None, label: str | None = None) -> str:
    """A booktabs tabular (wrapped in a table environment if a caption is given)."""
    align = align or "l" * len(header)
    body = ["\\begin{tabular}{" + align + "}", "\\toprule", " & ".join(header) + " \\\\", "\\midrule"]
    body += [" & ".join(str(c) for c in r) + " \\\\" for r in rows]
    body += ["\\bottomrule", "\\end{tabular}"]
    if caption is None:
        return "\n".join(body) + "\n"
    return "\n".join(["\\begin{table*}[t]", "\\centering", "\\small", *body, f"\\caption{{{caption}}}",
                      f"\\label{{{label}}}" if label else "", "\\end{table*}"]) + "\n"
